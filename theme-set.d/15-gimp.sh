#!/usr/bin/env bash
# shellcheck disable=SC1090,SC1091,SC2154
# shellcheck source=../lib/theme-env.sh

# GIMP theme hook - recolors GIMP 3's Default theme through the user gimp.css,
# which GIMP imports after the active theme on startup.

block_start="/* thpm-gimp-theme-start */"
block_end="/* thpm-gimp-theme-end */"

gimp_config_dirs() {
    local base
    local dir

    for base in "$HOME/.config/GIMP" "$HOME/.var/app/org.gimp.GIMP/config/GIMP"; do
        for dir in "$base"/3.*; do
            [[ -d "$dir" ]] && printf '%s\n' "$dir"
        done
    done
}

# Prints the file without the managed block. Writes go through `cat >` so a
# symlinked gimp.css (for example one kept in dotfiles) stays a symlink.
strip_managed_block() {
    local file="$1"

    awk -v start="$block_start" -v end="$block_end" '
        $0 == start { in_managed = 1; next }
        $0 == end { in_managed = 0; next }
        !in_managed { print }
    ' "$file"
}

cleanup_gimp_theme() {
    local dir
    local css_file
    local tmp_file

    while IFS= read -r dir; do
        css_file="$dir/gimp.css"
        [[ -f "$css_file" ]] || continue
        grep -Fqx "$block_start" "$css_file" || continue

        tmp_file="$(mktemp)"
        strip_managed_block "$css_file" > "$tmp_file"
        if grep -q '[^[:space:]]' "$tmp_file"; then
            cat "$tmp_file" > "$css_file"
        else
            rm -f "$css_file"
        fi
        rm -f "$tmp_file"
    done < <(gimp_config_dirs)
}

if [[ "${1:-}" == "--cleanup" ]]; then
    cleanup_gimp_theme
    exit 0
fi

source "${THPM_THEME_ENV:-$HOME/.local/share/thpm/lib/theme-env.sh}"

gimp_installed() {
    command -v gimp >/dev/null 2>&1 && return 0
    command -v gimp-3 >/dev/null 2>&1 && return 0
    command -v flatpak >/dev/null 2>&1 && flatpak info org.gimp.GIMP >/dev/null 2>&1
}

# Mix two hex colors (no '#'); amount is the percentage of the second color.
mix_hex() {
    local from="$1"
    local to="$2"
    local amount="$3"
    local r g b

    r=$(( (16#${from:0:2} * (100 - amount) + 16#${to:0:2} * amount + 50) / 100 ))
    g=$(( (16#${from:2:2} * (100 - amount) + 16#${to:2:2} * amount + 50) / 100 ))
    b=$(( (16#${from:4:2} * (100 - amount) + 16#${to:4:2} * amount + 50) / 100 ))
    rgb2hex "$r" "$g" "$b"
}

if ! gimp_installed; then
    skipped "GIMP"
fi

mapfile -t config_dirs < <(gimp_config_dirs)
if (( ${#config_dirs[@]} == 0 )); then
    # GIMP creates its versioned config directory on first launch.
    skipped "GIMP config directory"
fi

if [[ -f "$THPM_LIGHT_MODE_FILE" ]] || grep -Eq '^[[:space:]]*mode[[:space:]]*=[[:space:]]*"light"' "$input_file"; then
    shade=-1
else
    shade=1
fi

# Prefer Omarchy's named surface colors and fall back to shades of the
# background for themes that only define the base palette.
bg="$primary_background"
fg="$primary_foreground"
accent="$(extract_color accent)"
accent="${accent:-${normal_blue:-${cursor_color:-$fg}}}"
muted="$(extract_color muted)"
muted="${muted:-${bright_black:-$(mix_hex "$fg" "$bg" 50)}}"
selection="$(extract_color selection)"
selection="${selection:-${selection_background:-$(mix_hex "$bg" "$accent" 25)}}"
panel="$(extract_color lighter_background)"
panel="${panel:-$(change_shade "$bg" $(( shade * 12 )))}"
extreme="$(extract_color dark_background)"
extreme="${extreme:-$(change_shade "$bg" $(( shade * -6 )))}"
border="$(extract_color darker_background)"
border="${border:-$(change_shade "$bg" $(( shade * -12 )))}"
dimmed_fg="$(extract_color dark_foreground)"
dimmed_fg="${dimmed_fg:-$(mix_hex "$fg" "$bg" 30)}"

generated_block="$(cat << EOF
$block_start
/* Generated by thpm gimp plugin. Do not edit inside this block. */
@define-color fg-color               #${fg};
@define-color bg-color               #${panel};
@define-color border-color           #${border};

@define-color dimmed-fg-color        #${dimmed_fg};
@define-color disabled-fg-color      #${muted};
@define-color disabled-button-color  #$(mix_hex "$panel" "$muted" 50);

@define-color hover-color            #$(mix_hex "$panel" "$accent" 30);
@define-color widget-bg-color        #${bg};
@define-color selected-color         #${selection};

@define-color extreme-bg-color       #${extreme};
@define-color extreme-selected-color #$(mix_hex "$panel" "$fg" 10);

@define-color strong-border-color    #${extreme};
@define-color stronger-border-color  #$(mix_hex "$panel" "$fg" 15);
@define-color edge-border-color      #${border};

@define-color scrollbar-slider-color #${muted};
@define-color scrollbar-trough-color #${panel};

@define-color ruler-color            rgba($(hex2rgb "$border"), 0.3);

GimpToolButton:checked,
button.toggle:checked,
progressbar trough progress,
GimpSpinScale entry progress {
  background-color: #$(mix_hex "$panel" "$accent" 45);
}
$block_end
EOF
)"

for dir in "${config_dirs[@]}"; do
    css_file="$dir/gimp.css"
    tmp_file="$(mktemp)"

    # The managed block goes first so rules the user adds below it still win.
    printf '%s\n' "$generated_block" > "$tmp_file"
    if [[ -f "$css_file" ]]; then
        strip_managed_block "$css_file" >> "$tmp_file"
    fi
    cat "$tmp_file" > "$css_file"
    rm -f "$tmp_file"
done

success "GIMP theme updated!"

# GIMP 3 runs as a versioned binary (gimp-3.2), so look up the running name.
gimp_process="$(pgrep -xl 'gimp|gimp-3(\.[0-9]+)?' 2>/dev/null | awk 'NR == 1 { print $2 }')"
require_restart "${gimp_process:-gimp}" "GIMP"
exit 0
